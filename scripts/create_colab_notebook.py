                "    # Fallback: calculate bitrate from file size and duration (in kbps)\n",
                "    if source_bitrate <= 0 and duration > 0 and file_size_bytes > 0:\n",
                "        source_bitrate = int((file_size_bytes * 8) / (duration * 1000))\n",
