                "    for enc in legacy_candidates:\n",
                "        try:\n",
                "            candidate_text = raw_bytes.decode(enc)\n",
                "            score = _score(candidate_text)\n",
                "            if score > best_score:\n",
                "                best_score = score\n",
                "                best_text = candidate_text\n",
                "        except (UnicodeDecodeError, LookupError): continue\n",
                "    if best_score > 0 and best_text: return best_text\n",
                "    for enc in ['windows-1256', 'cp1256', 'utf-8']:\n",
                "        try: return raw_bytes.decode(enc, errors='replace')\n",
                "        except Exception: pass\n",
                "    return ''\n",
