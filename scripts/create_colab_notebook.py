                "        end_ass = _srt_ts_to_ass(tm.group(2))\n",
                "        text_parts = [_clean_line(tl) for tl in lines[timing_idx + 1:] if _clean_line(tl)]\n",
                "        if not text_parts: continue\n",
                "        text = '\\\\N'.join(text_parts)\n",
