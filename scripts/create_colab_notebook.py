                "def sanitize_subtitle_text(text):\n",
                "    \"\"\"Sanitize decoded subtitle text to eliminate libass rendering artifacts and tofu boxes ([]).\"\"\"\n",
                "    if not text: return ''\n",
                "    text = text.replace('\\x00', '').replace('\\r\\n', '\\n').replace('\\r', '\\n')\n",
                "    tofu_and_bidi_pattern = re.compile(r'[\\u200e\\u200f\\u202a-\\u202e\\u200b\\u200c\\u200d\\ufeff\\ufffe\\ufffd\\u061c\\u2066-\\u2069]')\n",
