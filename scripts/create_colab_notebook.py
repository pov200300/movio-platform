                "            try:\n",
                "                subprocess.run([ffmpeg_bin, '-y', '-sub_charenc', 'UTF-8', '-i', temp_src, temp_ass], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, check=False)\n",
                "                if os.path.exists(temp_ass) and os.path.getsize(temp_ass) > 0:\n",
                "                    with open(temp_ass, 'r', encoding='utf-8', errors='replace') as af:\n",
