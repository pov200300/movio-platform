                "def convert_srt_to_ass(srt_text, srt_path=None):\n",
                "    \"\"\"Convert SRT to ASS on 1080p canvas with high-visibility Arabic style. Resilient to null bytes, bidi marks, broken blocks.\"\"\"\n",
                "    if not srt_text: return ''\n",
                "    raw_text = srt_text.replace('\\x00', '').lstrip('\\ufeff\\ufffe').replace('\\r\\n', '\\n').replace('\\r', '\\n')\n",
                "    bidi_pattern = re.compile(r'[\\u200e\\u200f\\u061c\\u200b-\\u200d\\u202a-\\u202e\\u2066-\\u2069\\ufeff]')\n",
                "    cleaned = bidi_pattern.sub('', raw_text).strip()\n",
                "    if not cleaned: return ''\n",
                "    header_lines = [\n",
                "        \"[Script Info]\",\n",
                "        \"ScriptType: v4.00+\",\n",
                "        \"PlayResX: 1920\",\n",
                "        \"PlayResY: 1080\",\n",
                "        \"WrapStyle: 0\",\n",
                "        \"ScaledBorderAndShadow: yes\",\n",
                "        \"\",\n",
                "        \"[V4+ Styles]\",\n",
                "        \"Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\",\n",
                "        \"Style: Default,Noto Sans Arabic,76,&H00FFFFFF,&H000000FF,&H00000000,&H00000000,1,0,0,0,100,100,0,0,1,3.2,1,2,20,20,45,1\",\n",
                "        \"\",\n",
                "        \"[Events]\",\n",
                "        \"Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\",\n",
                "    ]\n",
                "    ass_header = '\\n'.join(header_lines) + '\\n'\n",
                "    time_pattern = re.compile(r'(\\d{1,2}:\\d{2}:\\d{2}[,.]\\d{1,3})\\s*(?:-->|->|—>|–>)\\s*(\\d{1,2}:\\d{2}:\\d{2}[,.]\\d{1,3})')\n",
                "    def _srt_ts_to_ass(ts):\n",
                "        ts = ts.replace(',', '.')\n",
                "        parts = ts.split(':')\n",
                "        h, mi = int(parts[0]), int(parts[1])\n",
                "        sec_parts = parts[2].split('.')\n",
                "        s = int(sec_parts[0])\n",
                "        ms_raw = sec_parts[1] if len(sec_parts) > 1 else '0'\n",
                "        cs = int(ms_raw.ljust(3, '0')[:3]) // 10\n",
                "        return f'{h}:{mi:02d}:{s:02d}.{cs:02d}'\n",
                "    def _clean_line(line):\n",
                "        c = re.sub(r'<[^>]+>', '', line.strip())\n",
