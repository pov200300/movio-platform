                "        lines = block.strip().split('\\n')\n",
                "        if len(lines) < 2: continue\n",
                "        tm = None\n",
                "        timing_idx = -1\n",
                "        for i, line in enumerate(lines):\n",
                "            tm = time_pattern.search(line)\n",
