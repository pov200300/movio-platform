                "    # Safe defaults if probe could not determine properties (in kbps)\n",
                "    if source_bitrate <= 0:\n",
                "        source_bitrate = 2500  # Default ~2500 kbps (2.5 Mbps)\n",
                "    if duration <= 0:\n",
                "        duration = 7200.0  # Default ~2 hours\n",
                "\n",
                "    return source_bitrate, duration\n",
